import { existsSync, statSync } from 'node:fs';
import { dirname, join, normalize, relative } from 'node:path';

const GITHUB_BLOB = 'https://github.com/ScraperNode/awesome-n8n-templates/blob/main/';
const N8N_SITE = 'https://n8n.io';
const ABSOLUTE = /^([a-z][a-z0-9+.-]*:|#|\/)/i;
const SITE_ROOT_RELATIVE = /^\/(?!\/)/;
const TEMPLATE_README = /^templates\/[^/]+\/[^/]+\/README\.md$/;
const HUB_ROOTS = ['templates', 'integrations', 'use-cases'];
const WORKFLOW_FILE = /^templates\/[^/]+\/[^/]+\/workflow\.json$/;
const DOC_PAGE = /^docs\/([^/]+?)(?:\.md)?$/;

const isDir = (path) => existsSync(path) && statSync(path).isDirectory();
const isFile = (path) => existsSync(path) && statSync(path).isFile();

/**
 * Maps a repo-relative path to its URL on the site, or null when the target
 * has no page. Markdown in this repo is written for GitHub, where links point
 * at files (`../../docs/importing-templates.md`, `workflow.json`); on the site
 * those files become directory routes.
 */
function siteUrl(root, base, target) {
  const abs = join(root, target);
  if (target === '' || target === '.' || target === 'README.md') {
    return base;
  }

  // README.md files render as their directory's page
  const dir = target.endsWith('/README.md') ? target.slice(0, -'/README.md'.length) : target;
  const hubRoot = dir.split('/')[0];
  if (HUB_ROOTS.includes(hubRoot) && isDir(join(root, dir)) && (dir === hubRoot || isFile(join(root, dir, 'README.md')))) {
    return `${base}${dir}/`;
  }

  // Docs render at /docs/<name>/, linked either as the .md file or the route
  const doc = target.match(DOC_PAGE);
  if (doc && isFile(join(root, 'docs', `${doc[1]}.md`))) {
    return `${base}docs/${doc[1]}/`;
  }

  // Template downloads are generated by src/pages/templates/[...slug]/workflow.json.ts
  if (WORKFLOW_FILE.test(target) && isFile(abs)) {
    return `${base}${target}`;
  }

  // Anything else that exists in the repo (LICENSE, CONTRIBUTING.md, ...) lives on GitHub
  if (isFile(abs)) {
    return `${GITHUB_BLOB}${target}`;
  }
  return null;
}

function decode(path) {
  try {
    return decodeURIComponent(path);
  } catch {
    return path;
  }
}

/**
 * Rewrites relative markdown links to absolute site URLs. Links whose target
 * doesn't exist (usually typos in third-party template descriptions, like a
 * bare `www.example.com`) are unwrapped to plain text instead of 404ing.
 */
export default function remarkSiteLinks({ root, base }) {
  return (tree, file) => {
    if (!file.path) {
      return;
    }
    const source = relative(root, file.path);
    const sourceDir = dirname(source);
    const isTemplateReadme = TEMPLATE_README.test(source);

    const resolve = (url) => {
      // Template descriptions come from n8n.io, where root-relative links are n8n.io pages
      if (url && isTemplateReadme && SITE_ROOT_RELATIVE.test(url)) {
        return `${N8N_SITE}${url}`;
      }
      if (!url || ABSOLUTE.test(url)) {
        return url;
      }
      const [path, hash] = url.split('#');
      const target = normalize(join(sourceDir, decode(path))).replace(/\/$/, '');
      if (target.startsWith('..')) {
        return null;
      }
      const resolved = siteUrl(root, base, target === '.' ? '' : target);
      return resolved && hash ? `${resolved}#${hash}` : resolved;
    };

    const visit = (node, parent) => {
      if (node.type === 'link' || node.type === 'definition') {
        const url = resolve(node.url);
        if (url) {
          node.url = url;
        } else if (node.type === 'link' && parent) {
          parent.children.splice(parent.children.indexOf(node), 1, ...node.children);
          return true;
        }
      }
      if (node.children) {
        for (let i = 0; i < node.children.length; i++) {
          // An unwrapped link puts its children in its place; revisit that index
          if (visit(node.children[i], node)) {
            i--;
          }
        }
      }
      return false;
    };
    visit(tree, null);
  };
}
